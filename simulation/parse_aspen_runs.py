"""
ChE 303: Fluid Particle Systems
Aspen Plus V14 Simulation Data Parser & Mass Balance Validator
Parses the 12 Aspen runs (run_1..6 and mix_1..6) generated by Charan.
"""

import os
import zipfile
import xml.etree.ElementTree as ET
import csv

def parse_aspen_xlsx(filepath):
    with zipfile.ZipFile(filepath, 'r') as z:
        ss = []
        if 'xl/sharedStrings.xml' in z.namelist():
            tree = ET.fromstring(z.read('xl/sharedStrings.xml'))
            ss = [elem.text for elem in tree.iter('{http://schemas.openxmlformats.org/spreadsheetml/2006/main}t')]
        
        tree = ET.fromstring(z.read('xl/worksheets/sheet1.xml'))
        rows = tree.findall('.//{http://schemas.openxmlformats.org/spreadsheetml/2006/main}row')
        grid = []
        for r in rows:
            row_vals = []
            for c in r.findall('{http://schemas.openxmlformats.org/spreadsheetml/2006/main}c'):
                t = c.get('t')
                v = c.find('{http://schemas.openxmlformats.org/spreadsheetml/2006/main}v')
                if v is not None:
                    val = v.text
                    if t == 's':
                        val = ss[int(val)] if int(val) < len(ss) else val
                    row_vals.append(val)
                else:
                    row_vals.append('')
            grid.append(row_vals)
        
        streams = grid[0][1:]
        
        # Mass flows (COFFEE solids)
        coffee_flows = {}
        total_flows = {}
        for r in grid:
            if r[0] == 'COFFEE' and len(r) > 2 and r[1] == 'kg/hr':
                for i, s in enumerate(streams):
                    if i + 2 < len(r) and r[i+2]:
                        try:
                            coffee_flows[s] = float(r[i+2])
                        except ValueError:
                            pass
            elif r[0] == 'Mass Flows' and len(r) > 2 and r[1] == 'kg/hr' and not total_flows:
                for i, s in enumerate(streams):
                    if i + 2 < len(r) and r[i+2]:
                        try:
                            total_flows[s] = float(r[i+2])
                        except ValueError:
                            pass
        
        # PSD table
        psd = {}
        for r in grid:
            if 'micron' in r[0]:
                bin_name = r[0].strip()
                psd[bin_name] = {}
                for i, s in enumerate(streams):
                    if i + 1 < len(r) and r[i+1]:
                        try:
                            psd[bin_name][s] = float(r[i+1])
                        except ValueError:
                            pass
        
        return {
            'filename': os.path.basename(filepath),
            'streams': streams,
            'coffee_flows': coffee_flows,
            'total_flows': total_flows,
            'psd': psd
        }

def main():
    aspen_dir = 'Aspen'
    if not os.path.exists(aspen_dir):
        aspen_dir = os.path.join(os.path.dirname(__file__), '..', 'Aspen')
    
    files = sorted([f for f in os.listdir(aspen_dir) if f.endswith('.xlsx')])
    print(f"Found {len(files)} Aspen Plus Excel result files.")
    
    summary_rows = []
    for f in files:
        res = parse_aspen_xlsx(os.path.join(aspen_dir, f))
        c_flows = res['coffee_flows']
        
        feed = c_flows.get('FEED', 97.0)
        crushed = c_flows.get('CRUSHED', 0.0)
        prod = c_flows.get('PROD', 0.0)
        fine = c_flows.get('FINE', 0.0)
        oversize = c_flows.get('OVERSIZE', 0.0)
        mixed = c_flows.get('MIXED', feed + oversize)
        
        # Yield and circulating load
        prod_yield_pct = (prod / feed) * 100.0 if feed else 0.0
        recirc_ratio = (oversize / feed) if feed else 0.0
        
        # PROD PSD fractions
        psd = res['psd']
        f_sub600 = psd.get('100 - 596.7  micron', {}).get('PROD', 0.0)
        f_600_1100 = psd.get('- 1093    micron', {}).get('PROD', 0.0)
        f_1100_1600 = psd.get('- 1590    micron', {}).get('PROD', 0.0)
        
        summary_rows.append({
            'file': f,
            'circuit_type': 'Closed-Loop (with Recycle)' if 'mix' in f else 'Open-Loop (Single-Pass)',
            'feed_coffee_kgh': round(feed, 2),
            'crusher_load_kgh': round(crushed, 2),
            'oversize_recycle_kgh': round(oversize, 2),
            'recirc_ratio': round(recirc_ratio, 3),
            'prod_coffee_kgh': round(prod, 2),
            'prod_yield_pct': round(prod_yield_pct, 1),
            'fine_byproduct_kgh': round(fine, 2),
            'prod_pct_100_597um': round(f_sub600 * 100, 2),
            'prod_pct_597_1093um': round(f_600_1100 * 100, 2),
            'prod_pct_1093_1590um': round(f_1100_1600 * 100, 2),
        })

    # Print summary table
    print("\n" + "="*110)
    print("               ASPEN PLUS V14 SOLID CIRCUIT SIMULATION SUMMARY (CHARAN'S RUNS)                ")
    print("="*110)
    header = f"{'File':<12} | {'Circuit Type':<26} | {'Crusher (kg/h)':<14} | {'Recycle (kg/h)':<14} | {'PROD (kg/h)':<11} | {'Yield (%)':<9} | {'Target Mode (600-1100 µm)'}"
    print(header)
    print("-" * 110)
    for r in summary_rows:
        print(f"{r['file']:<12} | {r['circuit_type']:<26} | {r['crusher_load_kgh']:<14} | {r['oversize_recycle_kgh']:<14} | {r['prod_coffee_kgh']:<11} | {r['prod_yield_pct']:<9} | {r['prod_pct_597_1093um']:.1f}%")
    print("="*110)

if __name__ == '__main__':
    main()
